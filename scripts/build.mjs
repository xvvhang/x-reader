import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const metadata = (await readFile(resolve(root, 'src/userscript.meta.js'), 'utf8')).trim();
const license = (await readFile(resolve(root, 'LICENSE'), 'utf8')).trim();
const result = await build({
  absWorkingDir: root,
  entryPoints: ['src/reader.js'],
  bundle: true,
  format: 'iife',
  target: 'es2022',
  charset: 'utf8',
  legalComments: 'none',
  write: false,
  banner: { js: `${metadata}\n\n// Generated by npm run build. Edit src/ instead of this file.\n\n/*!\n${license}\n*/` },
});
const output = result.outputFiles[0].text;
// Keep the existing root installation path as an identical compatibility copy.
const targets = ['dist/x-reader.user.js', 'x-reader.user.js'];
for (const target of targets) {
  const path = resolve(root, target);
  if (process.argv.includes('--check')) {
    const existing = await readFile(path, 'utf8').catch(() => null);
    if (existing !== output) throw new Error(`${target} is missing or outdated. Run npm run build.`);
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, output);
  }
}
console.log(process.argv.includes('--check') ? 'Generated userscripts are up to date.' : 'Built dist/x-reader.user.js and the root compatibility copy.');
